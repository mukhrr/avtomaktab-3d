import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { loadCatalogue, type CatalogueEntry } from '../../src/shared/signCatalogue';

export const BEGIN = '<!-- signs:credits begin (generated by npm run signs:credits, do not edit) -->';
export const END = '<!-- signs:credits end -->';
const RULES_URL = 'https://lex.uz/uz/docs/-5953883';

export interface CreditRow { number: string; page: string; licence: string; drawn: boolean }

export function creditRows(entries: CatalogueEntry[]): CreditRow[] {
  const rows: CreditRow[] = [];
  for (const e of entries) {
    const art = e.art;
    if (art?.source === 'commons') rows.push({ number: e.number, page: art.page, licence: art.licence, drawn: false });
    else if (art?.source === 'drawn' && art.basedOn) {
      if (!art.licence) throw new Error(`credits: ${e.number} is based on ${art.basedOn} but has no licence`);
      rows.push({ number: e.number, page: art.basedOn, licence: art.licence, drawn: true });
    }
  }
  return rows;
}

export function renderSection(entries: CatalogueEntry[]): string {
  const rows = creditRows(entries);
  const drawnOnly = entries.filter(e => e.art?.source === 'drawn' && !e.art.basedOn).length;
  const lines = [
    '## Road sign art',
    '',
    `The Rules text and the official sign sheets used as references are from lex.uz: ${RULES_URL}`,
    '',
    `${rows.length} signs use art from Wikimedia Commons, all public domain or CC0. Rows marked "edited" were copied to data/signs/drawn and changed (Uzbek text, values, small fixes). ${drawnOnly} more signs were drawn from scratch for this game.`,
    '',
    '| Sign | Commons page | Licence | Note |',
    '|---|---|---|---|',
    ...rows.map(r => `| ${r.number} | ${r.page} | ${r.licence} | ${r.drawn ? 'edited' : ''} |`),
    '',
  ];
  return lines.join('\n');
}

export function spliceSection(doc: string, section: string): string {
  const block = `${BEGIN}\n${section}${END}`;
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) return `${doc.replace(/\n*$/, '\n')}\n${block}\n`;
  return doc.slice(0, a) + block + doc.slice(b + END.length);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const doc = readFileSync('CREDITS.md', 'utf8');
  writeFileSync('CREDITS.md', spliceSection(doc, renderSection(loadCatalogue())));
  console.log('CREDITS.md road sign section written');
}
